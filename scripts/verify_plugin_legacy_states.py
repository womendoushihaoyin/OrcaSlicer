#!/usr/bin/env python3
"""Verify actual isolated Plater three-state acceptance after normal app exit.

No GUI is launched. Originals are retained; only the generated-by timestamp,
validated selector metadata and one exact appended canonical marker normalize.
This checks real Plater generation + production final-file postprocessing, not
interaction with the native Export SaveFileDialog. Tool contracts are separate
from a real GUI acceptance run.
"""
import argparse
from collections import Counter
import difflib
import hashlib
import json
import math
from pathlib import Path
import re
import time
import zipfile

WHEEL = "orca_dualhost_multi-1.0.0-py3-none-any.whl"
KEY = WHEEL[:-4]
WHEEL_SHA = "a1349e4d4493ed38bad8a7198c1fbecd09d4f868e65e7daf4494ee7da4da575f"
STL_SHA = "8f6176f7f70c5aa56a656437194b6869a58593e297954c381c85c9fcde7530bf"
MODULE_SHA = "0c7edbad9b8444196637bb8ee24e5c41e64841a50aeceaf2d2794e2fc61a7f06"
MARKER = "; ORCA_DUALHOST contract-v1 token=37"
CAPABILITIES = {"script", "pages", "slicing", "texture"}
STATES = ("uninstalled", "disabled", "enabled", "reopened")


def require(value, message):
    if not value:
        raise ValueError(message)


def selected_config(enabled):
    return {"plugins": f'"{KEY};;Dualhost Slice"' if enabled else "",
            "slicing_pipeline_plugin": '"Dualhost Slice"' if enabled else "",
            # PresetBundle::full_config() records exactly which print settings
            # differ from the system preset. Selecting a plugin adds its two
            # keys here. Validate the complete expected list; never discard an
            # arbitrary settings-difference field or accept unknown keys.
            "different_settings_to_system":
                "elefant_foot_compensation;initial_layer_print_height;" +
                ("plugins;print_plugin_config_overrides;slicing_pipeline_plugin;;" if enabled
                 else "print_plugin_config_overrides;;")}


def normalized_config(config, enabled):
    require(isinstance(config, dict) and len(config) > 10, "Missing resolved Print configuration")
    result = dict(config)
    for key, value in selected_config(enabled).items():
        require(result.get(key) == value, f"Incorrect persisted selector {key}: {result.get(key)!r}")
        del result[key]
    require(result.get("print_plugin_config_overrides") == "[]", "Unexpected per-print plugin override")
    return result


def normalized_gcode(data, enabled):
    # CRLF is not accepted silently: the same host/run must retain its exact
    # line endings. The canonical plugin itself appends a literal LF suffix.
    text = data.decode("utf-8", errors="strict")
    require("\r" not in text, "Unexpected line endings; no normalization rule is authorized")
    require(text.count(MARKER) == int(enabled), "Wrong canonical marker count")
    if enabled:
        suffix = "\n" + MARKER + "\n"
        require(text.endswith(suffix), "Canonical marker is not the exact final appended suffix")
        text = text[:-len(suffix)]
    generated = re.compile(r"(?m)^(; generated by [^\n]+ on )[^\n]+$")
    require(len(generated.findall(text)) == 1, "Missing/ambiguous generated-by timestamp")
    text = generated.sub(r"\1<timestamp>", text)
    for key, expected in selected_config(enabled).items():
        pattern = re.compile(r"(?m)^; " + re.escape(key) + r" = ([^\n]*)$")
        values = pattern.findall(text)
        require(values == [expected], f"Incorrect G-code selector {key}: {values!r}")
        text = pattern.sub("; " + key + " = <validated-selection>", text)
    return text.encode("utf-8")


def compare_model(left, right, tolerance=1e-6):
    """Only world-coordinate roundtrip float tolerance; no topology/metadata edits."""
    require(len(left) == len(right) == 1, "Expected exactly one real object")
    for a, b in zip(left, right):
        require({k: v for k, v in a.items() if k != "volumes"} ==
                {k: v for k, v in b.items() if k != "volumes"}, "Object metadata/config changed")
        require(len(a["volumes"]) == len(b["volumes"]) == 1 and a["instances"] == 1, "Object/part/instance count changed")
        for va, vb in zip(a["volumes"], b["volumes"]):
            require({k: v for k, v in va.items() if k != "world_triangles"} ==
                    {k: v for k, v in vb.items() if k != "world_triangles"}, "Part metadata/config changed")
            ta, tb = va["world_triangles"], vb["world_triangles"]
            require(len(ta) == len(tb) == 12, "Canonical 12-triangle geometry changed")
            for first, second in zip(ta, tb):
                require(len(first) == len(second) == 9 and
                        all(math.isfinite(x) and math.isfinite(y) and abs(x-y) <= tolerance for x, y in zip(first, second)),
                        "World-space geometry/winding changed beyond 1e-6 mm")
            points = [triangle[i:i+3] for triangle in ta for i in (0, 3, 6)]
            size = [max(p[a] for p in points)-min(p[a] for p in points) for a in range(3)]
            require(all(abs(x-y) <= tolerance for x, y in zip(size, (20, 20, 1))), "Unexpected canonical cube dimensions")


def verify_trace(events, pid):
    require(events and all(e["schema"] == 1 and e["pid"] == pid and e["module_sha256"] == MODULE_SHA for e in events),
            "Trace belongs to different code/process")
    sequences = [e["sequence"] for e in events]
    require(sequences == sorted(set(sequences)), "Trace reuses/resets callback sequence")
    for event in ("load", "unload"):
        require(Counter(e["capability"] for e in events if e["event"] == event) == Counter({x: 1 for x in CAPABILITIES}),
                f"Four capability {event} callbacks missing/duplicated")
    loads = [e["sequence"] for e in events if e["event"] == "load"]
    unloads = [e["sequence"] for e in events if e["event"] == "unload"]
    slices = [e for e in events if e["event"] == "slice" and e["capability"] == "slicing"]
    steps = Counter(e["payload"]["step"] for e in slices)
    require(steps["posSlice"] == steps["psGCodePostProcess"] == 2, "Expected two enabled real slice/postprocess jobs")
    require(all(max(loads) < e["sequence"] < min(unloads) and not e["payload"]["cancelled"] for e in slices),
            "Callbacks ran outside live capability lifetime")
    require(all(not e["thread"]["main"] for e in slices), "Slicing/postprocess callback unexpectedly ran on GUI thread")
    for event in slices:
        if event["payload"]["step"] == "posSlice":
            require(event["payload"]["has_print"] and event["payload"]["has_object"] and event["payload"]["layers"] > 0,
                    "Slice trace does not observe the actual Print/PrintObject")
    outputs = [e for e in events if e["event"] == "gcode"]
    require(len(outputs) == 2 and all(e["capability"] == "slicing" and e["payload"]["exists"] and
            e["payload"]["marker"] == MARKER for e in outputs), "Production final-file trace missing")
    lifecycle = [e["payload"] for e in events if e["event"] == "lifecycle" and e["capability"] == "slicing"]
    names = Counter(e["event"] for e in lifecycle)
    for start, end in (("SliceStarted", "SliceGeometryFinished"), ("GCodeExportStarted", "GCodeExportFinished")):
        require(names[start] == names[end] == 2, f"Unpaired actual Plater lifecycle: {start}/{end}")
        active = 0
        for event in lifecycle:
            if event["event"] == start:
                require(active == 0, f"Nested lifecycle {start}")
                active = 1
            elif event["event"] == end:
                require(active == 1 and event["code"] == "Ok", f"Failed/unpaired lifecycle {end}")
                active = 0
    require(names["ProjectBeforeSave"] == names["ProjectAfterSave"] == 1 and names["ObjectAdded"] >= 2 and
            names["SlicingJobComplete"] == 2, "Enabled GUI save/import/job lifecycle incomplete")
    return {"loads": 4, "unloads": 4, "enabled_slice_jobs": 2, "final_file_jobs": 2}


def verify(directory):
    directory = directory.resolve(strict=True)
    report = directory / "gui-legacy_states.json"
    evidence = json.loads(report.read_text(encoding="utf-8"))
    require(evidence["mode"] == "legacy_states" and evidence["ok"] and evidence["real_plater"] and
            evidence["empty_initial_catalog"] and evidence["normal_window_close"] and evidence["normal_close_completed"],
            "Actual isolated three-state GUI run/normal close did not finish")
    require(evidence["plugin_key"] == KEY and evidence["slicing_name"] == "Dualhost Slice" and evidence["enabled_capability_count"] == 4,
            "Unexpected canonical capability identity")
    files = {}
    def artifact(value):
        path = Path(value).resolve(strict=True)
        require(directory in path.parents, "Artifact escapes isolated run directory")
        require(path.is_file(), "Missing regular artifact")
        files[str(path.relative_to(directory))] = hashlib.sha256(path.read_bytes()).hexdigest()
        return path
    for key, digest in (("input_wheel", WHEEL_SHA), ("input_stl", STL_SHA), ("installed_entry", WHEEL_SHA)):
        path = artifact(evidence[key]); require(hashlib.sha256(path.read_bytes()).hexdigest() == digest, f"Pinned input bytes changed: {key}")
    rows = evidence["legacy_states"]
    require([e["state"] for e in rows] == list(STATES), "Missing/out-of-order actual state observations")
    comparison = directory / "legacy-states" / "comparison"
    comparison.mkdir(exist_ok=True)
    normalized = []
    configs = []
    for index, row in enumerate(rows):
        enabled = index >= 2
        require(row["layers"] > 0 and row["moves"] > 0 and row["export_timestamp_before"] != row["export_timestamp_after"],
                "Empty/cached slice accepted")
        if index < 3:
            require(row["registered_packages"] == int(index > 0) and row["loaded_capabilities"] == (4 if enabled else 0) and
                    row["trace_exists"] == enabled, "Uninstalled/disabled state ran plugin code")
            project = artifact(row["project"])
            with zipfile.ZipFile(project) as archive:
                require(archive.testzip() is None, "Saved 3MF is corrupt")
                cfg = json.loads(archive.read("Metadata/project_settings.config"))
                require(cfg["plugins"] == ([KEY+";;Dualhost Slice"] if enabled else []) and
                        cfg["slicing_pipeline_plugin"] == (["Dualhost Slice"] if enabled else []), "Saved 3MF lost actual selector")
        preview = artifact(row["raw_preview"]).read_bytes()
        final = artifact(row["gcode"]).read_bytes()
        require(row["marker_count"] == int(enabled), "Report marker count is inconsistent")
        if row["postprocess_route"] == "production_final_file_entry":
            require(MARKER.encode() not in preview and final == preview + (("\n"+MARKER+"\n").encode() if enabled else b""),
                    "Final-file output changed beyond the canonical appended marker")
        else:
            require(row["postprocess_route"] == "background_worker" and enabled and final == preview, "Unknown processing route")
        normalized.append(normalized_gcode(final, enabled))
        (comparison / (row["state"] + ".normalized.gcode")).write_bytes(normalized[-1])
        configs.append(normalized_config(row["print_config"], enabled))
        (comparison / (row["state"] + ".resolved-config.json")).write_text(json.dumps(configs[-1], indent=2)+"\n", encoding="utf-8")
        compare_model(rows[0]["model"], row["model"])
    diffs = []
    for index in range(1, 4):
        for kind, values in (("gcode", normalized), ("config", [json.dumps(c, sort_keys=True, indent=2).encode() for c in configs])):
            if values[index] != values[0]:
                target = comparison / (STATES[index] + "." + kind + ".diff")
                target.write_text("".join(difflib.unified_diff(values[0].decode().splitlines(True), values[index].decode().splitlines(True),
                    fromfile="uninstalled", tofile=STATES[index])), encoding="utf-8")
                diffs.append(str(target))
    require(not diffs, "Unexplained output/config differences retained: " + ", ".join(diffs))
    trace = artifact(evidence["trace"])
    trace_checks = verify_trace([json.loads(line) for line in trace.read_text(encoding="utf-8").splitlines()], evidence["pid"])
    # Existing check enforces isolated embedded Python, real OnExit/result=0,
    # PID gone, and macOS crash reports; it starts no process and opens no GUI.
    from verify_local_plugin_gui_smoke import verify as verify_normal_exit
    verify_normal_exit(directory, ["legacy_states"])
    from prepare_plugin_dualhost_gui import verify_process_exit
    startup = artifact(str(report)+".startup")
    exit_record = artifact(str(report)+".exit")
    artifact(report)
    artifact(directory / "LocalPluginSmoke-legacy_states.app/Contents/MacOS/Snapmaker_Orca")
    exit_check = verify_process_exit(evidence["pid"], startup.stat().st_mtime, exit_record.stat().st_mtime)
    exit_check["pid"] = evidence["pid"]
    return {"ok": True, "acceptance_complete": False, "delayed_crash_gate": "pending-recheck", "exit_check": exit_check, "mode": "legacy_states", "states": list(STATES), "actual_plater_slices": 4,
            "actual_project_saves": 3, "enabled_3mf_reopen": True, "export_save_file_dialog_tested": False,
            "trace": trace_checks, "input_and_output_sha256": files,
            "normalization": ["generated-by timestamp", "validated exact two plugin selectors and their complete expected preset-difference list", "single exact marker suffix"],
            "world_coordinate_tolerance_mm": 1e-6, "windows_linux_execution": "pending"}


def recheck_exit(directory):
    """Second independent read catches delayed macOS reports without rerunning GUI."""
    directory = directory.resolve(strict=True)
    result = json.loads((directory / "legacy-verification.json").read_text(encoding="utf-8"))
    require(result["ok"], "The primary acceptance verifier did not pass")
    check = result["exit_check"]
    require(time.time() >= check["checked_at_unix"] + 10, "Wait at least 10 seconds after the first verifier before the delayed crash check")
    for relative, digest in result["input_and_output_sha256"].items():
        path = (directory / relative).resolve(strict=True)
        require(directory in path.parents and hashlib.sha256(path.read_bytes()).hexdigest() == digest,
                "Acceptance input/evidence changed before delayed exit check: " + relative)
    from prepare_plugin_dualhost_gui import verify_process_exit
    result["delayed_exit_check"] = verify_process_exit(check["pid"], check["window_start_unix"], check["window_end_unix"])
    result["delayed_crash_gate"] = "passed"
    result["acceptance_complete"] = True
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--recheck-exit", action="store_true", help="Recheck the same PID/time window >=10 seconds after primary verification")
    args = parser.parse_args()
    try:
        result = recheck_exit(args.directory) if args.recheck_exit else verify(args.directory)
    except (ValueError, AssertionError, KeyError, OSError, UnicodeError, zipfile.BadZipFile) as error:
        result = {"ok": False, "error": str(error), "gui_pass_claimed": False}
    name = "legacy-final-verification.json" if args.recheck_exit else "legacy-verification.json"
    (args.directory / name).write_text(json.dumps(result, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
