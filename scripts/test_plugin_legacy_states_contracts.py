ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
import verify_plugin_legacy_states as gate


def gcode(enabled=False, stamp="2026-10-23 12:00:00"):
    lines = [f"; generated by SnapmakerOrca 2.4.1 on {stamp}", "G1 X10 Y20 E1"]
    lines += [f"; {k} = {v}" for k, v in gate.selected_config(enabled).items()]
    text = "\n".join(lines)+"\n"
    if enabled:
        text += "\n"+gate.MARKER+"\n"
    return text.encode()


def model():
    v = [(0, 0, 0), (20, 0, 0), (20, 20, 0), (0, 20, 0), (0, 0, 1), (20, 0, 1), (20, 20, 1), (0, 20, 1)]
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    return [{"name": "reference-cube", "instances": 1, "config": {}, "volumes": [
        {"name": "reference-cube", "type": 0, "config": {}, "world_triangles": [sum((list(v[i]) for i in f), []) for f in faces]}]}]


def trace():
    events = []
    def add(kind, capability="slicing", payload=None, main=False):
        events.append({"schema": 1, "pid": 123, "module_sha256": gate.MODULE_SHA, "sequence": len(events)+1,
            "event": kind, "capability": capability, "payload": payload or {}, "thread": {"main": main}})
    def lifecycle(name):
        add("lifecycle", payload={"event": name, "code": "Ok"})
    for capability in sorted(gate.CAPABILITIES): add("load", capability)
    lifecycle("ProjectBeforeSave"); lifecycle("ProjectAfterSave")
    for _ in range(2):
        lifecycle("ObjectAdded"); lifecycle("SliceStarted")
        add("slice", payload={"step": "posSlice", "has_print": True, "has_object": True, "layers": 5, "cancelled": False})
        lifecycle("SliceGeometryFinished"); lifecycle("GCodeExportStarted"); lifecycle("GCodeExportFinished")
        add("slice", payload={"step": "psGCodePostProcess", "cancelled": False})
        add("gcode", payload={"exists": True, "marker": gate.MARKER})
        lifecycle("SlicingJobComplete")
    for capability in sorted(gate.CAPABILITIES): add("unload", capability)
    return events


class EvidenceContracts(unittest.TestCase):
    def test_exact_allowed_difference(self):
        self.assertEqual(gate.normalized_gcode(gcode(), False), gate.normalized_gcode(gcode(True, "2026-10-24 01:00:00"), True))

    def test_machine_instruction_difference_survives(self):
        self.assertNotEqual(gate.normalized_gcode(gcode(), False), gate.normalized_gcode(gcode().replace(b"X10", b"X11"), False))

    def test_unknown_metadata_difference_survives(self):
        self.assertNotEqual(gate.normalized_gcode(gcode()+b"; unknown = a\n", False), gate.normalized_gcode(gcode()+b"; unknown = b\n", False))

    def test_duplicate_or_wrong_marker_rejected(self):
        for data in (gcode(True)+b"\n"+gate.MARKER.encode()+b"\n", gcode(True).replace(b"token=37", b"token=38"), gcode(True)+b"G1 X11\n"):
            with self.assertRaises(ValueError): gate.normalized_gcode(data, True)

    def test_disabled_marker_rejected(self):
        with self.assertRaises(ValueError): gate.normalized_gcode(gcode(True), False)

    def test_wrong_selection_rejected(self):
        with self.assertRaises(ValueError): gate.normalized_gcode(gcode(True).replace(b"Dualhost Slice", b"Other Slice"), True)

    def test_preset_difference_metadata_is_exact(self):
        for old, new in ((b"plugins;print_plugin_config_overrides", b"plugins;wall_loops;print_plugin_config_overrides"),
                         (b"elefant_foot_compensation;", b""),
                         (b"slicing_pipeline_plugin;;", b"slicing_pipeline_plugin;")):
            changed = gcode(True).replace(old, new)
            with self.assertRaises(ValueError): gate.normalized_gcode(changed, True)
        config = {str(i): "x" for i in range(15)} | gate.selected_config(True) | {"print_plugin_config_overrides": "[]"}
        config["different_settings_to_system"] += "unknown"
        with self.assertRaises(ValueError): gate.normalized_config(config, True)

    def test_duplicate_timestamp_or_unknown_line_endings_rejected(self):
        for data in (gcode()+b"; generated by Other on now\n", gcode().replace(b"\n", b"\r\n")):
            with self.assertRaises(ValueError): gate.normalized_gcode(data, False)

    def test_model_float_roundtrip_tolerance(self):
        left = model(); right = copy.deepcopy(left)
        right[0]["volumes"][0]["world_triangles"][0][0] += 1e-7
        gate.compare_model(left, right)

    def test_model_shape_winding_metadata_changes_rejected(self):
        for change in ("coordinate", "winding", "config"):
            left = model(); right = copy.deepcopy(left)
            if change == "coordinate": right[0]["volumes"][0]["world_triangles"][0][0] += .001
            elif change == "winding":
                t = right[0]["volumes"][0]["world_triangles"][0];t[3:6], t[6:9] = t[6:9], t[3:6]
            else: right[0]["config"]["wall_loops"] = "3"
            with self.assertRaises(ValueError): gate.compare_model(left, right)

    def test_actual_trace_contract_shape(self):
        self.assertEqual(gate.verify_trace(trace(), 123)["final_file_jobs"], 2)

    def test_trace_wrong_identity_or_thread_rejected(self):
        for change in ("pid", "code", "thread"):
            events = trace()
            if change == "pid": events[0]["pid"] = 456
            elif change == "code": events[0]["module_sha256"] = "bad"
            else: next(e for e in events if e["event"] == "slice")["thread"]["main"] = True
            with self.assertRaises(ValueError): gate.verify_trace(events, 123)

    def test_trace_missing_dispatch_or_unload_rejected(self):
        for kind in ("unload", "gcode", "slice"):
            events = trace(); events.pop(next(i for i, e in enumerate(events) if e["event"] == kind))
            with self.assertRaises(ValueError): gate.verify_trace(events, 123)

    def test_trace_forged_finished_without_start_rejected(self):
        events = trace()
        next(e for e in events if e["event"] == "lifecycle" and e["payload"]["event"] == "SliceStarted")["payload"]["event"] = "SliceGeometryFinished"
        with self.assertRaises(ValueError): gate.verify_trace(events, 123)

    def test_unknown_config_changes_survive(self):
        config = {str(i): "x" for i in range(15)} | gate.selected_config(False) | {"print_plugin_config_overrides": "[]"}
        other = dict(config); other["unrelated"] = "changed"
        self.assertNotEqual(gate.normalized_config(config, False), gate.normalized_config(other, False))

    def test_delayed_gate_requires_elapsed_time(self):
        with tempfile.TemporaryDirectory() as temp:
            p = Path(temp)
            (p / "legacy-verification.json").write_text(json.dumps({"ok": True, "exit_check": {"checked_at_unix": time.time()}}))
            with self.assertRaisesRegex(ValueError, "10 seconds"): gate.recheck_exit(p)

    def test_delayed_gate_rejects_changed_evidence(self):
        with tempfile.TemporaryDirectory() as temp:
            p = Path(temp); (p / "evidence").write_bytes(b"changed")
            (p / "legacy-verification.json").write_text(json.dumps({"ok": True,
                "exit_check": {"checked_at_unix": time.time()-20}, "input_and_output_sha256": {"evidence": "wrong"}}))
            with self.assertRaisesRegex(ValueError, "changed"): gate.recheck_exit(p)

    def test_delayed_gate_rechecks_original_pid_window(self):
        import prepare_plugin_dualhost_gui as shared
        with tempfile.TemporaryDirectory() as temp:
            p = Path(temp)
            (p / "legacy-verification.json").write_text(json.dumps({"ok": True,
                "exit_check": {"pid": 123, "checked_at_unix": time.time()-20, "window_start_unix": 100, "window_end_unix": 110},
                "input_and_output_sha256": {}}))
            with patch.object(shared, "verify_process_exit", side_effect=ValueError("Delayed crash detected")) as check:
                with self.assertRaisesRegex(ValueError, "Delayed crash"): gate.recheck_exit(p)
                check.assert_called_once_with(123, 100, 110)
            with patch.object(shared, "verify_process_exit", return_value={"pid_absent": True}):
                result = gate.recheck_exit(p)
                self.assertTrue(result["acceptance_complete"])

    def test_shared_exit_checker_rejects_live_pid_and_recent_crash(self):
        import prepare_plugin_dualhost_gui as shared
        with patch.object(shared, "pid_present", return_value=True):
            with self.assertRaisesRegex(ValueError, "still present"): shared.verify_process_exit(123, 100)
        with tempfile.TemporaryDirectory() as temp:
            p = Path(temp)
            (p / "Snapmaker_Orca-contract.ips").write_text('{"pid":123}\n')
            with patch.object(shared, "pid_present", return_value=False), patch.object(shared.sys, "platform", "darwin"):
                with self.assertRaisesRegex(ValueError, "crash report"): shared.verify_process_exit(123, time.time()-30, crash_directory=p)

    def test_prepare_rejects_used_profile_before_app_mutations(self):
        spec = importlib.util.spec_from_file_location("prepare_test", ROOT / "prepare_local_plugin_gui_smoke.py")
        prepare = importlib.util.module_from_spec(spec); spec.loader.exec_module(prepare)
        with tempfile.TemporaryDirectory() as temp:
            output = Path(temp) / "new-run"; (output / "data_dir").mkdir(parents=True)
            args = ["prepare", "--binary", "missing", "--python-root", "missing", "--output-dir", str(output), "--mode", "legacy_states", "--fixture", gate.WHEEL]
            with patch.object(sys, "argv", args), patch.object(sys, "platform", "darwin"), patch.object(prepare.subprocess, "run") as calls:
                with self.assertRaises(SystemExit) as caught: prepare.main()
                self.assertEqual(caught.exception.code, 2); calls.assert_not_called()
            self.assertEqual(list(output.iterdir()), [output / "data_dir"])

    def test_prepare_rejects_changed_canonical_bytes(self):
        spec = importlib.util.spec_from_file_location("prepare_test", ROOT / "prepare_local_plugin_gui_smoke.py")
        prepare = importlib.util.module_from_spec(spec); spec.loader.exec_module(prepare)
        with tempfile.TemporaryDirectory() as temp:
            output = Path(temp) / "new-run"; fixture = Path(temp) / gate.WHEEL; fixture.write_bytes(b"changed")
            args = ["prepare", "--binary", "missing", "--python-root", "missing", "--output-dir", str(output), "--mode", "legacy_states", "--fixture", str(fixture)]
            with patch.object(sys, "argv", args), patch.object(sys, "platform", "darwin"), patch.object(prepare.subprocess, "run") as calls:
                with self.assertRaises(SystemExit) as caught: prepare.main()
                self.assertEqual(caught.exception.code, 2); calls.assert_not_called()
            self.assertFalse(output.exists())


if __name__ == "__main__":
    unittest.main()
