#!/usr/bin/env python3
"""Sequential CLI + headless production-component measurements, never GUI startup.

Use --prepare-only to generate a reviewable plan without executing a host. Use
--validation-only for functional checks whose timings are not baseline samples.
Formal samples require an explicit idle acknowledgement; no build is launched.
"""
