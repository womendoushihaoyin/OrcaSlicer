STATES = ("none", "disabled", "enabled")
PHASES = ("cli-help", "cli-slice", "native-startup", "native-slice", "native-mesh", "native-callbacks")

def digest(path):
    value = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""): value.update(chunk)
    return value.hexdigest()

def save(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

def percentile(values, fraction=.95):
    if not values or not 0 < fraction <= 1: raise ValueError("Nonempty samples and a valid percentile are required")
    return sorted(values)[max(0, math.ceil(fraction * len(values)) - 1)]

def stats(values):
    return {"n": len(values), "min": min(values), "median": statistics.median(values),
            "p95_nearest_rank": percentile(values), "max": max(values),
            "p95_sample_warning": "exploratory; fewer than 20 samples" if len(values) < 20 else None}

def normalized_gcode(data):
    # Preserve all commands, values, comments and config except this proven clock field.
    # Do not erase arbitrary comments/path strings/numbers to manufacture equivalence.
    text = data.decode("utf-8").replace("\r\n", "\n")
    text = re.sub(r"(?m)^(; generated by .+? on )[^\n]+$", r"\1<timestamp>", text)
    return text.encode("utf-8")

def compare_gcode(left, right, output, allowed_metadata=()):
    a, b = Path(left).read_bytes(), Path(right).read_bytes()
    na, nb = normalized_gcode(a), normalized_gcode(b)
    target = Path(output)
    target.mkdir(parents=True, exist_ok=True)
    (target / "left.normalized.gcode").write_bytes(na)
    (target / "right.normalized.gcode").write_bytes(nb)
    difference = list(difflib.unified_diff(na.decode().splitlines(True), nb.decode().splitlines(True), fromfile="left", tofile="right"))
    (target / "normalized.diff").write_text("".join(difference), encoding="utf-8")
    def without_known_metadata(data):
        return b"".join(line for line in data.splitlines(True) if not any(
            re.match(rb"^; " + key.encode("ascii") + rb" =", line) for key in allowed_metadata))
    metadata_only = bool(allowed_metadata) and without_known_metadata(na) == without_known_metadata(nb)
    return {"equal": na == nb, "equivalent": na == nb or metadata_only,
            "classification": "identical" if na == nb else "declared_native_plugin_selection_metadata_only" if metadata_only else "unexplained_difference",
            "allowed_metadata": list(allowed_metadata), "raw_sha256": [hashlib.sha256(a).hexdigest(), hashlib.sha256(b).hexdigest()],
            "normalized_sha256": [hashlib.sha256(na).hexdigest(), hashlib.sha256(nb).hexdigest()],
            "diff": str(target / "normalized.diff"), "normalization": "CRLF and generated-by timestamp only"}

def equivalence_by_phase(comparisons):
    phases = {item["candidate"].split("/", 1)[0] for item in comparisons}
    return {phase: all(item["equivalent"] for item in comparisons if item["candidate"].startswith(phase + "/"))
            for phase in sorted(phases)}

def make_png():
    def chunk(name, data): return struct.pack(">I", len(data)) + name + data + struct.pack(">I", zlib.crc32(name + data))
    raw = (b"\x00" + b"\xff" * 512) * 512
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 512, 512, 8, 0, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")

def fixtures(destination, source):
    destination.mkdir(parents=True, exist_ok=False)
    template = source.read_text(encoding="utf-8")
    result = {"schema": 1, "template_sha256": digest(source), "packages": []}
    for kind in ("script", "pages", "slicing", "texture"):
        name = "orca_benchmark_" + kind
        info = name + "-1.0.0.dist-info"
        code = template.replace('CAPABILITY = "script"', f'CAPABILITY = "{kind}"').encode("utf-8")
        files = {name + "/__init__.py": code,
                 info + "/METADATA": f"Metadata-Version: 2.1\nName: {name}\nVersion: 1.0.0\nRequires-Python: >=3.12\n\n".encode(),
                 info + "/WHEEL": b"Wheel-Version: 1.0\nGenerator: Orca-local-benchmark\nRoot-Is-Purelib: true\nTag: py3-none-any\n",
                 info + "/top_level.txt": (name + "\n").encode()}
        if kind == "texture": files[name + "/textures/height-纹理.png"] = make_png()
        record = io.StringIO(); writer = csv.writer(record, lineterminator="\n")
        for key, value in sorted(files.items()):
            writer.writerow([key, "sha256=" + base64.urlsafe_b64encode(hashlib.sha256(value).digest()).rstrip(b"=").decode(), len(value)])
        writer.writerow([info + "/RECORD", "", ""]); files[info + "/RECORD"] = record.getvalue().encode()
        path = destination / (name + "-1.0.0-py3-none-any.whl")
        with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
            for key, value in sorted(files.items()):
                entry = zipfile.ZipInfo(key, (2020, 1, 1, 0, 0, 0)); entry.compress_type = zipfile.ZIP_DEFLATED
                archive.writestr(entry, value)
        result["packages"].append({"kind": kind, "file": path.name, "sha256": digest(path), "source_sha256": hashlib.sha256(code).hexdigest()})
    save(destination / "manifest.json", result)
    return result

def project_contract(path):
    with zipfile.ZipFile(path) as archive:
        config = json.loads(archive.read("Metadata/project_settings.config"))
    for key in ("plugins", "slicing_pipeline_plugin"):
        if config.get(key) not in (None, [], "", [""]):
            raise ValueError(f"CLI comparison project must have no selected plugins: {key}")
    return {"sha256": digest(path), "printer": config.get("printer_settings_id"), "process": config.get("print_settings_id"),
            "plugins": config.get("plugins"), "slicing_pipeline_plugin": config.get("slicing_pipeline_plugin")}

def child_environment():
    env = os.environ.copy()
    for key in list(env):
        if key.startswith("ORCA_LOCAL_PLUGIN_SMOKE"): env.pop(key)
    env.update(UV_OFFLINE="1", PYTHONNOUSERSITE="1", SLIC3R_LOGLEVEL="0")
    return env

def measure(command, cwd, log, timeout):
    started = time.perf_counter(); usage = None; timed_out = False
    with Path(log).open("wb") as stream:
        process = subprocess.Popen(command, cwd=cwd, env=child_environment(), stdout=stream, stderr=subprocess.STDOUT,
            start_new_session=os.name != "nt", creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)
        if hasattr(os, "wait4"):
            while True:
                pid, status, usage = os.wait4(process.pid, os.WNOHANG)
                if pid:
                    process.returncode = os.waitstatus_to_exitcode(status); break
                if time.perf_counter() - started > timeout:
                    timed_out = True; os.killpg(process.pid, signal.SIGKILL)
                    _, status, usage = os.wait4(process.pid, 0); process.returncode = os.waitstatus_to_exitcode(status); break
                time.sleep(.001)
        else:
            try: process.wait(timeout=timeout)
            except subprocess.TimeoutExpired:
                timed_out = True; process.kill(); process.wait()
    return {"exit_code": process.returncode, "timed_out": timed_out,
            "wall_seconds": time.perf_counter() - started,
            "cpu_seconds": usage.ru_utime + usage.ru_stime if usage else None,
            "child_rusage_maxrss_bytes": int(usage.ru_maxrss * (1 if sys.platform == "darwin" else 1024)) if usage else None,
            "memory_scope": "wait4 ru_maxrss (maximum resident child image; not summed process-tree memory)" if usage else "pending: no wait4 on this platform",
            "log": str(log)}

def stage_cli(binary, resources, destination):
    # macOS dev binary's source-relative Resources is absent. Give the unchanged executable a
    # private, minimal bundle layout; direct CLI exec still uses its linked production code.
    if sys.platform == "darwin":
        target = destination / "Host.app/Contents/MacOS" / binary.name
        target.parent.mkdir(parents=True); shutil.copy2(binary, target)
        (target.parent.parent / "Resources").symlink_to(resources, target_is_directory=True)
        if digest(target) != digest(binary): raise ValueError("Binary changed while copying; stop builds before collecting")
        return target
    return binary  # Packaged Linux/Windows prerequisites stay in their existing read-only layout.

def aggregate(samples):
    groups = {}
    for sample in samples:
        if sample.get("warmup") or not sample.get("passed"): continue
        group = groups.setdefault(sample["group"], {})
        for key in ("wall_seconds", "cpu_seconds", "child_rusage_maxrss_bytes"):
            if sample.get(key) is not None: group.setdefault(key, []).append(sample[key])
        for stage, value in sample.get("native", {}).get("stages", {}).items():
            if value.get("passed"): group.setdefault("stage_ms/" + stage, []).append(value["milliseconds"])
    return {group: {key: stats(values) for key, values in metrics.items()} for group, metrics in groups.items()}

def run(args):
    output = args.output.absolute(); output.mkdir(parents=True, exist_ok=False)
    source = Path(__file__).resolve().parents[1]
    package_manifest = fixtures(output / "fixtures", source / "tests/plugin_benchmark/package.py")
    phases = args.phase or list(PHASES)
    report = {"schema": 1, "mode": "plan" if args.prepare_only else "functional_validation" if args.validation_only else "baseline",
        "clock": "perf_counter; native stages use steady_clock", "os": sys.platform, "machine": platform.machine(),
        "os_release": platform.release(), "logical_cpus": os.cpu_count(), "load_average_start": os.getloadavg() if hasattr(os, "getloadavg") else None,
        "scope": {"cli": "official ON/OFF CLI process; CLI has no PluginManager initialization",
                  "native": "headless production components; sequential package loading; Print::process in TBB arena(1)",
                  "gui_cold_start": "pending", "os_cache_cold_start": "pending; no cache purge or reboot",
                  "webview_render": "pending", "numpy_bulk_mesh": "pending", "device_callbacks": "pending",
                  "long_running_leak_growth": "pending; bounded callback batch and process peak only"},
        "cache_policy": "new process and cloned prepared isolated profile each run; warm OS filesystem cache, no cold-cache claim",
        "packages": package_manifest, "phases": phases, "samples": [], "setup": [], "comparisons": [], "passed": False,
        "candidate_targets": {"GUI_empty_plugin_startup_increment_5pct": "pending GUI measurement",
                              "no_plugin_slice_increment_2pct": "candidate only; report CLI delta after output equivalence, do not claim full GUI gate"}}
    def persist(): save(output / "results.json", report)
    persist()
    if args.prepare_only: print("Prepared fixtures and pending plan; no host process executed"); return 0
    if not args.validation_only and not args.idle_confirmed:
        raise ValueError("Formal sampling requires --idle-confirmed after GUI/build jobs stop; use --validation-only for diagnostics")
    binaries = {}
    if any(phase.startswith("cli-") for phase in phases):
        if not args.on_cli or not args.off_cli or not args.resources: raise ValueError("CLI phases need --on-cli --off-cli --resources")
        for state, path in (("on", args.on_cli), ("off", args.off_cli)):
            original = path.resolve(strict=True); resources = args.resources.resolve(strict=True)
            binaries[state] = stage_cli(original, resources, output / "hosts" / state)
            report.setdefault("binaries", {})[state] = {"source": str(original), "run": str(binaries[state]), "sha256": digest(original)}
        if digest(binaries["on"]) == digest(binaries["off"]): raise ValueError("ON and OFF must be distinct official binaries")
        report["resources"] = str(resources)
    if "cli-slice" in phases:
        if not args.project: raise ValueError("CLI slicing requires --project, a valid self-contained plugin-free 3MF")
        report["project"] = project_contract(args.project)
        report["cli_version_policy"] = "Explicit --allow-newer-file: this release exports 2.4.0.1 projects while its CLI identifies as 01.10.01.50; original project bytes are unchanged"
        project = output / "reference.3mf"; shutil.copy2(args.project, project)
    if any(phase.startswith("native-") for phase in phases):
        if not args.native: raise ValueError("Native phases require --native orca_plugin_benchmark")
        native = args.native.resolve(strict=True)
        report.setdefault("binaries", {})["native"] = {"path": str(native), "sha256": digest(native)}
        for state in STATES:
            profile = output / "prepared-profiles" / state; target = output / "setup" / state
            target.mkdir(parents=True)
            command = [str(native), "prepare", state, "startup", str(output / "fixtures"), str(profile), str(target / "native.json"), str(args.calls), str(args.grid)]
            result = measure(command, source, target / "prepare.log", args.timeout)
            result.update(state=state, command=command, excluded_from_baseline=True)
            report["setup"].append(result); persist()
            if result["exit_code"] != 0: raise RuntimeError("Native profile preparation failed; see setup log")
            payload = json.loads((target / "native.json").read_text(encoding="utf-8"))
            if not payload.get("passed"): raise RuntimeError("Native preparation did not confirm production components")
    persist()
    repeats = 1 if args.validation_only else args.repetitions
    warmups = 0 if args.validation_only else args.warmups
    jobs = []
    for phase in phases:
        for state in (("off", "on") if phase.startswith("cli-") else ("enabled",) if phase == "native-callbacks" else STATES): jobs.append((phase, state))
    for repeat in range(-warmups, repeats):
        # Alternate matched cases to reduce order bias; no concurrent hosts or slices.
        for phase, state in (jobs if repeat % 2 == 0 else list(reversed(jobs))):
            label = f"{phase}-{state}-{repeat}"; target = output / "runs" / label
            target.mkdir(parents=True); profile = target / "profile"
            sample = {"group": phase + "/" + state, "repeat": repeat, "warmup": repeat < 0, "passed": False}
            if phase.startswith("cli-"):
                profile.mkdir(); command = [str(binaries[state]), "--datadir", str(profile), "--outputdir", str(target / "export")]
                (target / "export").mkdir()
                command += ["--help"] if phase == "cli-help" else ["--allow-newer-file", "--slice", "1", str(project)]
            else:
                shutil.copytree(output / "prepared-profiles" / state, profile)
                command = [str(native), "run", state, phase.removeprefix("native-"), str(output / "fixtures"), str(profile), str(target / "native.json"), str(args.calls), str(args.grid)]
            sample.update(measure(command, source, target / "process.log", args.timeout)); sample["command"] = command
            sample["passed"] = sample["exit_code"] == 0 and not sample["timed_out"]
            if sample["passed"] and phase.startswith("native-"):
                sample["native"] = json.loads((target / "native.json").read_text(encoding="utf-8"))
                sample["passed"] = sample["native"].get("passed", False)
            if sample["passed"] and phase.endswith("slice"):
                candidates = list(target.rglob("*.gcode"))
                if len(candidates) != 1:
                    sample["passed"] = False; sample["error"] = f"Expected one real G-code output, found {len(candidates)}"
                else:
                    raw = candidates[0].read_bytes()
                    if not re.search(rb"(?m)^G[0123]\s", raw):
                        sample["passed"] = False; sample["error"] = "No real G-code move commands"
                    sample["gcode"] = str(candidates[0]); sample["gcode_sha256"] = digest(candidates[0])
            report["samples"].append(sample); persist()
            print(label, "PASS" if sample["passed"] else "FAIL", flush=True)
    for phase in ("cli-slice", "native-slice"):
        relevant = [s for s in report["samples"] if s["group"].startswith(phase + "/") and s["passed"] and not s["warmup"]]
        if not relevant: continue
        reference = next((s for s in relevant if s["group"].endswith("/off" if phase == "cli-slice" else "/none")), None)
        if reference is None: continue
        for index, sample in enumerate(relevant):
            allowed_metadata = ("plugins", "slicing_pipeline_plugin") if phase == "native-slice" and sample["group"].endswith("/enabled") else ()
            comparison = compare_gcode(reference["gcode"], sample["gcode"], output / "diffs" / f"{phase}-{index}", allowed_metadata)
            comparison.update(reference=reference["group"], candidate=sample["group"], repeat=sample["repeat"])
            report["comparisons"].append(comparison)
    report["aggregates"] = {} if args.validation_only else aggregate(report["samples"])
    report["algorithm_equivalence_by_phase"] = equivalence_by_phase(report["comparisons"])
    report["algorithm_equivalence"] = all(report["algorithm_equivalence_by_phase"].values()) if report["comparisons"] else None
    groups = report["aggregates"]
    if "cli-slice/off" in groups and "cli-slice/on" in groups:
        off = groups["cli-slice/off"]["wall_seconds"]["median"]; on = groups["cli-slice/on"]["wall_seconds"]["median"]
        report["cli_slice_median_increment_pct"] = (on / off - 1.) * 100.
        report["candidate_cli_2pct_review"] = "output mismatch: resolve algorithm difference first" if report["algorithm_equivalence_by_phase"].get("cli-slice") is False else "needs review" if on > off * 1.02 else "within candidate; GUI scope still pending"
    report["load_average_end"] = os.getloadavg() if hasattr(os, "getloadavg") else None
    report["passed"] = all(s["passed"] for s in report["samples"]) and report["algorithm_equivalence"] is not False
    persist()
    return 0 if report["passed"] else 1

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("on-cli", "off-cli", "resources", "native", "project", "output"): parser.add_argument("--" + name, type=Path, required=name == "output")
    parser.add_argument("--phase", action="append", choices=PHASES)
    parser.add_argument("--repetitions", type=int, default=5); parser.add_argument("--warmups", type=int, default=1)
    parser.add_argument("--calls", type=int, default=1000); parser.add_argument("--grid", type=int, default=256)
    parser.add_argument("--timeout", type=float, default=180)
    parser.add_argument("--prepare-only", action="store_true"); parser.add_argument("--validation-only", action="store_true")
    parser.add_argument("--idle-confirmed", action="store_true")
    args = parser.parse_args()
    if args.repetitions < 1 or args.warmups < 0 or not 1 <= args.calls <= 1000000 or not 1 <= args.grid <= 2048 or args.timeout <= 0: parser.error("Invalid workload bounds")
    try: return run(args)
    except Exception as error: print("Benchmark incomplete:", error, file=sys.stderr); return 1
if __name__ == "__main__": raise SystemExit(main())
