#!/usr/bin/env python3
"""Utility contracts only: no real-host performance claims."""
import importlib.util
import json
import os
from pathlib import Path
import sys
import tempfile
import unittest
import zipfile

spec=importlib.util.spec_from_file_location("benchmark_plugin_host",Path(__file__).with_name("benchmark_plugin_host.py"))
b=importlib.util.module_from_spec(spec);spec.loader.exec_module(b)
class Contracts(unittest.TestCase):
    def test_percentile(self):
        self.assertEqual(b.percentile(list(range(1,21))),19)
        self.assertEqual(b.percentile([3,1,2]),3)
        self.assertIsNotNone(b.stats([1,2,3])["p95_sample_warning"])
        self.assertIsNone(b.stats(list(range(20)))["p95_sample_warning"])
        with self.assertRaises(ValueError):b.percentile([])
    def test_normalization_is_narrow(self):
        a=b'; generated by Same 1.0 on 2026-01-01\r\nG1 X10 Y20 E1\r\n; wall_loops = 2\r\n'
        c=b'; generated by Same 1.0 on 2026-02-02\nG1 X10 Y20 E1\n; wall_loops = 2\n'
        self.assertEqual(b.normalized_gcode(a),b.normalized_gcode(c))
        for changed in (c.replace(b'X10',b'X11'),c.replace(b'E1',b'E1.1'),c.replace(b'wall_loops = 2',b'wall_loops = 3'),c.replace(b'Same 1.0',b'Same 1.1')):
            self.assertNotEqual(b.normalized_gcode(a),b.normalized_gcode(changed))
    def test_diff_keeps_numerical_difference(self):
        with tempfile.TemporaryDirectory(prefix='benchmark-中文-') as root:
            root=Path(root);a=root/'a.gcode';c=root/'c.gcode';a.write_bytes(b'G1 X1\n');c.write_bytes(b'G1 X2\n')
            result=b.compare_gcode(a,c,root/'diff')
            self.assertFalse(result['equal']);self.assertIn('G1 X2',Path(result['diff']).read_text())
    def test_native_metadata_is_declared_not_hidden(self):
        with tempfile.TemporaryDirectory() as root:
            root=Path(root);a=root/'a';c=root/'c'
            a.write_bytes(b'G1 X1\n; plugins = \n');c.write_bytes(b'G1 X1\n; plugins = package;;cap\n')
            strict=b.compare_gcode(a,c,root/'strict')
            allowed=b.compare_gcode(a,c,root/'allowed',('plugins',))
            self.assertFalse(strict['equivalent']);self.assertFalse(allowed['equal']);self.assertTrue(allowed['equivalent'])
            self.assertIn('package;;cap',Path(allowed['diff']).read_text())
            c.write_bytes(b'G1 X1.01\n; plugins = package;;cap\n')
            self.assertFalse(b.compare_gcode(a,c,root/'changed',('plugins',))['equivalent'])
    def test_cli_and_native_equivalence_stay_separate(self):
        values=[{"candidate":"cli-slice/off","equivalent":True},
                {"candidate":"cli-slice/on","equivalent":True},
                {"candidate":"native-slice/none","equivalent":False}]
        self.assertEqual(b.equivalence_by_phase(values),{"cli-slice":True,"native-slice":False})
        self.assertEqual(b.equivalence_by_phase([]),{})
    def test_fixtures_repeatable(self):
        with tempfile.TemporaryDirectory(prefix='benchmark-中文-') as root:
            root=Path(root);source=Path(__file__).resolve().parents[1]/'tests/plugin_benchmark/package.py'
            a=b.fixtures(root/'a',source);c=b.fixtures(root/'b',source)
            self.assertEqual(a,c);self.assertEqual(len(a['packages']),4)
            texture=next(x for x in a['packages'] if x['kind']=='texture')
            with zipfile.ZipFile(root/'a'/texture['file']) as z:
                png=z.read('orca_benchmark_texture/textures/height-纹理.png')
                self.assertTrue(png.startswith(b'\x89PNG'))
                self.assertIn('CAPABILITY = "texture"',z.read('orca_benchmark_texture/__init__.py').decode())
    def test_project_rejects_selected_plugin(self):
        with tempfile.TemporaryDirectory() as root:
            for plugins in ([],['package;;cap']):
                path=Path(root)/('clean.3mf' if not plugins else 'enabled.3mf')
                with zipfile.ZipFile(path,'w') as z:z.writestr('Metadata/project_settings.config',json.dumps({'plugins':plugins,'slicing_pipeline_plugin':[]}))
                if plugins:
                    with self.assertRaises(ValueError):b.project_contract(path)
                else:self.assertEqual(b.project_contract(path)['plugins'],[])
    def test_environment_is_child_only(self):
        original=dict(os.environ);env=b.child_environment();self.assertEqual(dict(os.environ),original)
        self.assertEqual(env['UV_OFFLINE'],'1')
    def test_measure_isolated_child(self):
        with tempfile.TemporaryDirectory() as root:
            result=b.measure([sys.executable,'-c','print("utility child")'],root,Path(root)/'child.log',5)
            self.assertEqual(result['exit_code'],0);self.assertFalse(result['timed_out'])
            self.assertGreater(result['wall_seconds'],0)
            if hasattr(os,'wait4'):self.assertGreater(result['child_rusage_maxrss_bytes'],0)
    def test_aggregate_excludes_warmup_failure(self):
        samples=[{'group':'x','passed':True,'warmup':True,'wall_seconds':99},
                 {'group':'x','passed':False,'wall_seconds':88},
                 {'group':'x','passed':True,'wall_seconds':2,'native':{'stages':{'phase':{'milliseconds':5,'passed':True}}}}]
        result=b.aggregate(samples);self.assertEqual(result['x']['wall_seconds']['n'],1)
        self.assertEqual(result['x']['stage_ms/phase']['median'],5)
if __name__=='__main__':unittest.main()
